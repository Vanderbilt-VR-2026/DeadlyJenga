using System;
using System.Linq;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEditor.SceneManagement;
using System.IO;
namespace DeadlyJenga.CastlePrototype.Editor
{
    [InitializeOnLoad]
    public static class CrossProcessBuild
    {
        const string LobbyHandoffKey = "DeadlyJenga.LobbyHandoffFixture";
        const string LobbyHandoffExitCode = LobbyHandoffKey + ".ExitCode";
        static CrossProcessBuild()
        {
            if (SessionState.GetBool(LobbyHandoffKey, false)) EditorApplication.update += PollLobbyHandoff;
            EditorApplication.playModeStateChanged += state =>
            {
                if (state != PlayModeStateChange.EnteredEditMode) return;
                int code = SessionState.GetInt(LobbyHandoffExitCode, -1);
                if (code < 0) return;
                SessionState.EraseInt(LobbyHandoffExitCode);
                EditorApplication.Exit(code);
            };
        }
        public static void RunLobbyHandoffBatch()
        {
            string scene = AssetDatabase.FindAssets("Home t:Scene").Select(AssetDatabase.GUIDToAssetPath)
                .Single(path => Path.GetFileNameWithoutExtension(path) == "Home");
            SessionState.SetBool(LobbyHandoffKey, true);
            EditorApplication.update += PollLobbyHandoff;
            EditorSceneManager.OpenScene(scene);
            EditorApplication.EnterPlaymode();
        }
        static void PollLobbyHandoff()
        {
            if (!EditorApplication.isPlaying) return;
            var args = Environment.GetCommandLineArgs();
            var folder = args.Single(a => a.StartsWith("--dj-smoke-dir=")).Substring(15);
            var role = args.Single(a => a.StartsWith("--dj-smoke=")).Substring(11);
            string file = Path.Combine(folder, role + ".txt");
            if (!File.Exists(file)) return;
            var report = File.ReadAllLines(file);
            if (!report.Any(line => line.StartsWith("COMPLETE ") || line.StartsWith("FAILED "))) return;
            SessionState.SetBool(LobbyHandoffKey, false);
            EditorApplication.update -= PollLobbyHandoff;
            // Let Play Mode teardown remove assets generated by platform packages.
            SessionState.SetInt(LobbyHandoffExitCode, report.Any(line => line.StartsWith("COMPLETE ")) ? 0 : 2);
            EditorApplication.ExitPlaymode();
        }

        // Builds the smoke player without exiting the editor, so an open editor can run the harness.
        public static string BuildSmokePlayer(string exePath, bool scriptsOnly)
        {
            var scenes = EditorBuildSettings.scenes.Where(s => s.enabled).Select(s => s.path).ToArray();
            // OpenXR build validation fails unless Composition Layers is on for the build (same as RunBatch).
            var composition = UnityEngine.XR.OpenXR.OpenXRSettings
                .GetSettingsForBuildTargetGroup(BuildTargetGroup.Standalone)
                ?.GetFeatures<UnityEngine.XR.OpenXR.Features.OpenXRFeature>()
                .FirstOrDefault(feature => feature.GetType().Name == "OpenXRCompositionLayersFeature");
            bool compositionWasEnabled = composition && composition.enabled;
            try
            {
                if (composition) composition.enabled = true;
                var build = BuildPipeline.BuildPlayer(new BuildPlayerOptions
                {
                    scenes = scenes, locationPathName = exePath,
                    target = BuildTarget.StandaloneWindows64,
                    options = BuildOptions.Development | (scriptsOnly ? BuildOptions.BuildScriptsOnly : BuildOptions.None)
                });
                return build.summary.result + " " + build.summary.totalSize + " bytes " + build.summary.totalTime;
            }
            finally
            {
                if (composition) composition.enabled = compositionWasEnabled;
            }
        }

        // Runs a real host and guest on the same LAN adapter, with isolated logs per invocation.
        public static void RunNearbyPairBatch()
        {
            if (!UnityEngine.Application.isBatchMode)
                throw new InvalidOperationException("Use a dedicated batch editor for this check.");
            string output = Path.GetFullPath(Path.Combine("Logs", "Validation", "NearbyPair-" + Guid.NewGuid().ToString("N")));
            Directory.CreateDirectory(output);
            string report = Path.Combine(output, "pair.txt");
            string exe = Path.GetFullPath(Path.Combine("Builds", "IntegrationSweep", "DeadlyJenga.exe"));
            var players = new System.Collections.Generic.List<System.Diagnostics.Process>();
            int exitCode = 1;
            try
            {
                string build = BuildSmokePlayer(exe, false);
                File.WriteAllText(report, "Player build " + build + Environment.NewLine);
                if (!build.StartsWith("Succeeded ", StringComparison.Ordinal) || !File.Exists(exe))
                    throw new InvalidOperationException("Standalone development build failed: " + build);
                foreach (string role in new[] { "host", "guest" })
                {
                    string log = Path.Combine(output, role + "-player.log");
                    var info = new System.Diagnostics.ProcessStartInfo(exe,
                        $"-batchmode -force-d3d11 -screen-width 640 -screen-height 360 -logFile \"{log}\" --dj-smoke={role} \"--dj-smoke-dir={output}\" --dj-nearby-lobby")
                    {
                        UseShellExecute = false, CreateNoWindow = true,
                        WindowStyle = System.Diagnostics.ProcessWindowStyle.Hidden
                    };
                    var player = System.Diagnostics.Process.Start(info);
                    players.Add(player);
                    File.AppendAllText(report, $"{role} pid={player.Id}\n");
                }
                var elapsed = System.Diagnostics.Stopwatch.StartNew();
                while (players.Any(player => !player.HasExited))
                {
                    if (players.Any(player => player.HasExited && player.ExitCode != 0))
                        throw new InvalidOperationException("A peer exited with a failure. See its role report.");
                    if (elapsed.Elapsed.TotalMinutes > 21) throw new TimeoutException("Two-player check timed out.");
                    System.Threading.Thread.Sleep(500);
                }
                foreach (string role in new[] { "host", "guest" })
                {
                    var lines = File.ReadAllLines(Path.Combine(output, role + ".txt"));
                    if (!lines.Any(line => line.StartsWith("COMPLETE ", StringComparison.Ordinal)) ||
                        lines.Any(line => line.StartsWith("FAILED ") || line.StartsWith("FAIL ")))
                        throw new InvalidOperationException(role + " did not finish its gameplay checks.");
                }
                if (players.Any(player => player.ExitCode != 0)) throw new InvalidOperationException("Peer exit failure.");
                File.AppendAllText(report, "PASS independent nearby host and guest completed\n");
                exitCode = 0;
            }
            catch (Exception error)
            {
                File.AppendAllText(report, "FAIL " + error + Environment.NewLine);
            }
            finally
            {
                foreach (var player in players)
                {
                    if (!player.HasExited) player.Kill();
                    player.Dispose();
                }
            }
            EditorApplication.Exit(exitCode);
        }

        public static void RunBatch()
        {
            bool poseProbe = Environment.GetCommandLineArgs().Contains("--dj-pose-probe");
            var scenes = EditorBuildSettings.scenes.Where(s => s.enabled).Select(s => s.path);
            var composition = (poseProbe || Environment.GetCommandLineArgs().Contains("--dj-tycoon") ||
                Environment.GetCommandLineArgs().Contains("--dj-full-round")) ? UnityEngine.XR.OpenXR.OpenXRSettings
                .GetSettingsForBuildTargetGroup(BuildTargetGroup.Standalone)
                ?.GetFeatures<UnityEngine.XR.OpenXR.Features.OpenXRFeature>()
                .FirstOrDefault(feature => feature.GetType().Name == "OpenXRCompositionLayersFeature") : null;
            bool compositionWasEnabled = composition && composition.enabled;
            try
            {
                if (composition) composition.enabled = true;
                if (poseProbe) scenes = scenes.OrderBy(path => System.IO.Path.GetFileNameWithoutExtension(path) == "Lobby" ? 0 : 1);
                var build = BuildPipeline.BuildPlayer(new BuildPlayerOptions
                {
                    scenes = scenes.ToArray(), locationPathName = "Builds/IntegrationSweep/DeadlyJenga.exe",
                    target = BuildTarget.StandaloneWindows64, options = BuildOptions.Development | (Environment.GetCommandLineArgs().Contains("--dj-scripts-only") ? BuildOptions.BuildScriptsOnly : BuildOptions.None)
                });
                if (build.summary.result != BuildResult.Succeeded)
                    throw new Exception("Independent player build failed: " + build.summary.result);
            }
            finally
            {
                if (composition) composition.enabled = compositionWasEnabled;
            }
            EditorApplication.Exit(0);
        }
    }
}
